export function getBaremeForDate(region: RegionType, annee: number, mois: number): BaremePeriode {
  const dateRef = `${annee}-${String(mois).padStart(2, '0')}-01`;
  const found = BAREMES_OFFICIELS.find(
    (b) => b.region === region && b.dateDeb <= dateRef && b.dateFin >= dateRef
  );
  if (found) return found;
  return BAREMES_OFFICIELS.find((b) => b.region === region) || BAREMES_OFFICIELS[0];
}

/**
 * Calcule les jours fériés français pour une année donnée
 */
export function getJoursFeries(annee: number, region: RegionType): Record<string, string> {
  const feries: Record<string, string> = {};
  const fmt = (m: number, d: number) =>
    `${annee}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`;

  feries[fmt(1, 1)] = 'Jour de l’An';
  feries[fmt(5, 1)] = 'Fête du Travail (1er Mai)';
  feries[fmt(5, 8)] = 'Victoire 1945';
  feries[fmt(7, 14)] = 'Fête Nationale';
  feries[fmt(8, 15)] = 'Assomption';
  feries[fmt(11, 1)] = 'Toussaint';
  feries[fmt(11, 11)] = 'Armistice 1918';
  feries[fmt(12, 25)] = 'Noël';

  if (region === 'Alsace-Moselle') {
    feries[fmt(12, 26)] = 'Saint-Étienne (Alsace-Moselle)';
  }

  const a = annee % 19;
  const b = Math.floor(annee / 100);
  const c = annee % 100;
  const d = Math.floor(b / 4);
  const e = b % 4;
  const f = Math.floor((b + 8) / 25);
  const g = Math.floor((b - f + 1) / 3);
  const h = (19 * a + b - d - g + 15) % 30;
  const i = Math.floor(c / 4);
  const k = c % 4;
  const l = (32 + 2 * e + 2 * i - h - k) % 7;
  const m = Math.floor((a + 11 * h + 22 * l) / 451);
  const monthPaques = Math.floor((h + l - 7 * m + 114) / 31);
  const dayPaques = ((h + l - 7 * m + 114) % 31) + 1;

  const datePaques = new Date(annee, monthPaques - 1, dayPaques);
  const addDays = (base: Date, days: number) => {
    const dt = new Date(base);
    dt.setDate(dt.getDate() + days);
    return fmt(dt.getMonth() + 1, dt.getDate());
  };

  if (region === 'Alsace-Moselle') {
    feries[addDays(datePaques, -2)] = 'Vendredi Saint (Alsace-Moselle)';
  }
  feries[addDays(datePaques, 1)] = 'Lundi de Pâques';
  feries[addDays(datePaques, 39)] = 'Ascension';
  feries[addDays(datePaques, 50)] = 'Lundi de Pentecôte';

  return feries;
}

